<?php
#Tipos de operadores
$a = 10;
$b = 20;

#Operadores aritméticos: +, -, *, /, %, **
echo $a + $b;
echo $a - $b;
echo $a * $b;
echo $a / $b;
echo $a % $b;
echo $a ** $b;

#Operadores de asignación
$a += $b;
$a -= $b;
$a *= $b;
$a /= $b;
$a %= $b;
$a **= $b;

#operadores de comparación (relacionales)
echo $a == $b;
echo $a != $b;
echo $a > $b;
echo $a < $b;
echo $a >= $b;
echo $a <= $b;

#operadores lógicos
echo $a && $b;
echo $a || $b;
echo !$a;
